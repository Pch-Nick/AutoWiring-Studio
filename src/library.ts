export const CATEGORIES = [...new Set(LIBRARY.map(l => l.category))]
export const SWITCHES = new Set(['hydfront','hydrear','mechfront','mechrear','startbtn','killswitch','hazard','mainswitch','sidestand','clutchsw','brakelever','brakepedal','clutchbtn','hornbtn'])
export function parsePins(spec: string): Pin[] {
  const raw = spec.split('|'); const half = Math.ceil(raw.length / 2)
  return raw.map((p, i) => { const [number, name, fn] = p.split(':')
    return { id: `p${i}`, number, name, fn: (fn as Fn) || 'sig', side: i < half ? 'left' : 'right' } })
}
export function makeData(item: LibItem): CompData {
  return { libId: item.id, name: item.name, category: item.category, pins: parsePins(item.pins),
    switchState: SWITCHES.has(item.id) ? (['killswitch','mainswitch'].includes(item.id) ? 'closed' : 'open') : undefined, source: 'library', verified: true }
}
